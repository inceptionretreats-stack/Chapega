/** Ordered by first appearance in the catalogue, with no separate enum to sync. */
export const CATALOGUE_CATEGORIES: readonly ProductCategory[] = Object.freeze(
  Array.from(new Set(CATALOGUE_PRODUCTS.map((product) => product.category))),
);

const productById: ReadonlyMap<string, Product> = new Map(
  CATALOGUE_PRODUCTS.map((product) => [product.id, product]),
);

export function getProductById(productId: string): Product | undefined {
  return productById.get(productId);
}

export function getProductsByCategory(category: ProductCategory): readonly Product[] {
  return CATALOGUE_PRODUCTS.filter((product) => product.category === category);
}

const fs = require("node:fs/promises");
const path = require("node:path");
const sharp = require("sharp");

const directory = __dirname;
const repository = path.resolve(directory, "../../..");
const background = "#7a263a";

function svg(body, { expanded = false, rounded = false, filled = false, labelled = false } = {}) {
  const viewBox = expanded ? "-128 -128 1280 1280" : "0 0 1024 1024";
  const label = labelled ? ' role="img" aria-label="Chapega.com"' : "";
  const backdrop = filled
    ? `<rect width="1024" height="1024"${rounded ? ' rx="224"' : ""} fill="${background}"/>\n`
    : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"${label}>\n${backdrop}${body}\n</svg>\n`;
}

function attributes(element) {
  return Object.fromEntries(
    [...element.matchAll(/([\w-]+)="([^"]*)"/g)].map((match) => [match[1], match[2]]),
  );
}

function roundedRectanglePath(rectangle) {
  const x = Number(rectangle.x);
  const y = Number(rectangle.y);
  const width = Number(rectangle.width);
  const height = Number(rectangle.height);
  const radius = Math.min(Number(rectangle.rx || 0), width / 2, height / 2);
  if (![x, y, width, height, radius].every(Number.isFinite)) {
    throw new Error("The canonical logo contains an invalid rectangle.");
  }
  return `M${x + radius},${y}H${x + width - radius}Q${x + width},${y} ${x + width},${y + radius}V${y + height - radius}Q${x + width},${y + height} ${x + width - radius},${y + height}H${x + radius}Q${x},${y + height} ${x},${y + height - radius}V${y + radius}Q${x},${y} ${x + radius},${y}Z`;
}

function notificationVector(mark) {
  const paths = [...mark.matchAll(/<path\b[^>]*\/>/g)].map((match) => attributes(match[0]));
  const knot = [...mark.matchAll(/<rect\b[^>]*\/>/g)].map((match) => attributes(match[0]));
  if (paths.length !== 4 || knot.length !== 1) {
    throw new Error("Review the notification-vector conversion after changing the mark's structure.");
  }
  // The ribbon strips are already inside the solid C; white-on-white adds
  // no silhouette. Keep the two bows' even-odd holes in the monochrome mark.
  const silhouette = [paths[0], paths[2], paths[3], { d: roundedRectanglePath(knot[0]) }];
  const elements = silhouette.map(
    (element) =>
      `        <path android:fillColor="#FFFFFFFF"${element["fill-rule"] === "evenodd" ? ' android:fillType="evenOdd"' : ""} android:pathData="${element.d}" />`,
  );
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/assets/branding/render-branding.cjs from mark.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="1024" android:viewportHeight="1024">
    <group android:pivotX="517" android:pivotY="522"
        android:scaleX="1.15" android:scaleY="1.15"
        android:translateX="-5" android:translateY="-10">
${elements.join("\n")}
    </group>
</vector>
`;
}

async function writePng(source, destination, size, opaque = false) {
  let pipeline = sharp(Buffer.from(source), { density: 192 }).resize(size, size);
  pipeline = opaque ? pipeline.flatten({ background }).removeAlpha() : pipeline.ensureAlpha();
  await pipeline.png().toFile(destination);
}

async function writeWebFallbacks(variants, body) {
  await fs.writeFile(
    path.join(repository, "app/icon.svg"),
    svg(body, { rounded: true, filled: true, labelled: true }),
  );
  await writePng(
    variants["icon-full-bleed"],
    path.join(repository, "app/apple-icon.png"),
    180,
    true,
  );
  for (const size of [192, 512]) {
    await writePng(variants.icon, path.join(repository, `public/icons/icon-${size}.png`), size);
  }
  await writePng(
    variants["icon-foreground"],
    path.join(repository, "public/icons/icon-maskable-512.png"),
    512,
    true,
  );

  const sizes = [16, 32, 48, 256];
  const frames = await Promise.all(
    sizes.map((size) =>
      sharp(Buffer.from(variants.icon), { density: 192 })
        .resize(size, size)
        .ensureAlpha()
        .png()
        .toBuffer(),
    ),
  );
  // ICO permits PNG image payloads. Zero in a dimension byte represents 256px.
  const directory = Buffer.alloc(6 + frames.length * 16);
  directory.writeUInt16LE(1, 2);
  directory.writeUInt16LE(frames.length, 4);
  let offset = directory.length;
  for (const [index, frame] of frames.entries()) {
    const entry = 6 + index * 16;
    directory[entry] = sizes[index] === 256 ? 0 : sizes[index];
    directory[entry + 1] = directory[entry];
    directory.writeUInt16LE(1, entry + 4);
    directory.writeUInt16LE(32, entry + 6);
    directory.writeUInt32LE(frame.length, entry + 8);
    directory.writeUInt32LE(offset, entry + 12);
    offset += frame.length;
  }
  await fs.writeFile(path.join(repository, "app/favicon.ico"), Buffer.concat([directory, ...frames]));
}

async function main() {
  const mark = await fs.readFile(path.join(directory, "mark.svg"), "utf8");
  const match = mark.match(/<svg\b[^>]*>([\s\S]*)<\/svg>/);
  if (!match) throw new Error("The canonical mark must be an SVG document.");
  const body = match[1].trim();
  const monochrome = body.replace(/fill="#[\da-fA-F]+"/g, 'fill="#fff"');
  const variants = {
    icon: svg(body, { rounded: true, filled: true }),
    "icon-full-bleed": svg(body, { filled: true }),
    "icon-foreground": svg(body, { expanded: true }),
    "icon-monochrome": svg(monochrome, { expanded: true }),
  };
  if (process.argv.includes("--web-only")) {
    await writeWebFallbacks(variants, body);
    process.stdout.write("Rendered web favicon, Apple touch icon and PWA icons.\n");
    return;
  }
  for (const [name, source] of Object.entries(variants)) {
    await fs.writeFile(path.join(directory, `${name}.svg`), source);
    await writePng(source, path.join(directory, `${name}.png`), 1024, name === "icon-full-bleed");
  }
  await writePng(variants["icon-full-bleed"], path.join(directory, "store-icon-512.png"), 512);
  await writeWebFallbacks(variants, body);
  const launchDirectory = path.join(repository, "mobile/ios/Runner/Assets.xcassets/LaunchImage.imageset");
  for (const [suffix, size] of [["", 120], ["@2x", 240], ["@3x", 360]]) {
    await writePng(variants.icon, path.join(launchDirectory, `LaunchImage${suffix}.png`), size);
  }
  await fs.writeFile(
    path.join(repository, "mobile/android/app/src/main/res/drawable/ic_stat_chapega.xml"),
    notificationVector(body),
  );
  const details = await sharp(path.join(directory, "store-icon-512.png")).metadata();
  if (details.width !== 512 || details.height !== 512 || !details.hasAlpha) {
    throw new Error("Play icon must be a 512×512 RGBA PNG.");
  }
  process.stdout.write("Rendered branding masters, Play icon, web icons, iOS launch images and Android notification vector.\n");
}

main().catch((error) => {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
});
